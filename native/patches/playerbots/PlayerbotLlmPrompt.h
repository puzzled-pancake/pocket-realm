/** banklib.compose twin (full shape: says/events/results head, [Memories]
 * tail (last 6), [State], and the [BRIDGE AI] note legs that S5's bridge
 * overlay will call with lines/fills/extra - identical string semantics,
 * so the byte-diff gate covers the S5 composition too). */
inline std::string ComposeUserTurn(std::string const& player,
    std::vector<std::string> const& says, std::vector<std::string> const& events,
    std::vector<std::string> const& results, std::string const& state,
    std::vector<std::string> const& mems, std::vector<std::string> const& lines,
    std::string const& fills, std::string const& extra)
{
    std::string head;
    for (size_t i = 0; i < says.size(); ++i)
        head += "[say] " + says[i] + "\n";
    for (size_t i = 0; i < events.size(); ++i)
        head += "[EVENT] " + events[i] + "\n";
    for (size_t i = 0; i < results.size(); ++i)
        head += "[RESULT] " + results[i] + "\n";
    std::string body = player.empty() ? std::string() : player + "\n";
    body += head;
    while (!body.empty() && body.back() == '\n')
        body.pop_back();                       // body.rstrip("\n")

    std::string tail;
    if (!mems.empty())
    {
        tail += "\n[Memories] ";
        size_t const first = mems.size() > 6 ? mems.size() - 6 : 0;
        for (size_t i = first; i < mems.size(); ++i)
        {
            if (i > first) tail += "; ";
            tail += mems[i];
        }
    }
    if (!state.empty())
        tail += "\n[State] " + state;

    std::string note;
    if (!lines.empty())
    {
        note = "\n[BRIDGE AI] ";
        if (!extra.empty())
            note += extra + "\n";
        note += "Speak your reply, then end it with exactly these lines - "
                "copy the ready ones as they are:\n";
        for (size_t i = 0; i < lines.size(); ++i)
        {
            if (i) note += "\n";
            note += lines[i];
        }
        if (!fills.empty())
            note += "\n" + fills;
    }
    else if (!extra.empty())
    {
        note = "\n[BRIDGE AI] " + extra +
               "\n(For this reply only. Never mention this instruction.)";
    }
    return body + tail + note;
}

/** One prior conversation turn for the request body. */
struct HistoryTurn
{
    bool assistant = false;
    std::string content;

    HistoryTurn() {}
    HistoryTurn(bool isAssistant, std::string const& text)
        : assistant(isAssistant), content(text) {}
};

/** Per-tier request knobs (A6 + SS2.1/SS4.3). providerSafe strips the
 * llama.cpp-only fields for external endpoints that may reject unknown
 * body keys; thinkingKwargs emits chat_template_kwargs enable_thinking
 * false for model families whose export template defaults to thinking
 * (SS4.4 - the qwen family). */
struct RequestSampling
{
    float temperature = 1.0f;
    float topP = 0.95f;
    int topK = 64;
    float repeatPenalty = 1.0f;
    float minP = 0.0f;
    float presencePenalty = 0.0f;
    int maxTokens = 200;
    bool thinkingKwargs = false;
    bool providerSafe = false;
};

inline std::string JsonNumber(double value)
{
    // a conf-parsed nan/inf must never reach the body text:
    // "temperature":nan is invalid JSON and would silence every
    // generation with no diagnostic (value != value catches NaN)
    if (!(value == value) || value > 1e18 || value < -1e18)
        return "1";
    if (value == static_cast<double>(static_cast<long long>(value)))
        return std::to_string(static_cast<long long>(value));
    char buf[32];
    std::snprintf(buf, sizeof(buf), "%g", value);
    return buf;
}

/** The A4 native chat-request body: one JSON builder, no conf-string
 * surgery. Message order: system, prior turns (oldest first), the current
 * user turn LAST. Field order mirrors the app template S1 pinned. */
inline std::string BuildChatRequestBody(std::string const& model,
    std::string const& system, std::vector<HistoryTurn> const& history,
    std::string const& user, RequestSampling const& s)
{
    std::string out = "{\"model\":\"";
    out += EscapeJsonString(model);
    out += "\",\"messages\":[{\"role\":\"system\",\"content\":\"";
    out += EscapeJsonString(system);
    out += "\"}";
    for (HistoryTurn const& turn : history)
    {
        out += ",{\"role\":\"";
        out += turn.assistant ? "assistant" : "user";
        out += "\",\"content\":\"";
        out += EscapeJsonString(turn.content);
        out += "\"}";
    }
    out += ",{\"role\":\"user\",\"content\":\"";
    out += EscapeJsonString(user);
    out += "\"}],\"max_tokens\":";
    out += std::to_string(s.maxTokens);
    out += ",\"temperature\":" + JsonNumber(s.temperature);
    out += ",\"top_p\":" + JsonNumber(s.topP);
    if (!s.providerSafe)
    {
        out += ",\"top_k\":" + std::to_string(s.topK);
        out += ",\"repeat_penalty\":" + JsonNumber(s.repeatPenalty);
        if (s.minP > 0.0f)
            out += ",\"min_p\":" + JsonNumber(s.minP);
        if (s.presencePenalty > 0.0f)
            out += ",\"presence_penalty\":" + JsonNumber(s.presencePenalty);
    }
    if (s.thinkingKwargs)
        out += ",\"chat_template_kwargs\":{\"enable_thinking\":false}";
    out += ",\"cache_prompt\":true,\"stream\":false}";
    return out;
}

