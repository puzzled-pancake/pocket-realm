// zlib-compatible crc32 (poly 0xEDB88320, init/final-xor 0xFFFFFFFF):
// the variant/bible selection must match banklib's zlib.crc32 exactly or
// a bot would train on one TOOLS_NOTE example block and ship with another.
inline uint32_t Crc32(char const* data, size_t len)
{
    uint32_t crc = 0xFFFFFFFFu;
    for (size_t i = 0; i < len; ++i)
    {
        crc ^= static_cast<unsigned char>(data[i]);
        for (int bit = 0; bit < 8; ++bit)
            crc = (crc >> 1) ^ (0xEDB88320u & (0u - (crc & 1u)));
    }
    return crc ^ 0xFFFFFFFFu;
}

inline uint32_t Crc32Str(std::string const& s)
{
    return Crc32(s.data(), s.size());
}

/** banklib.TIER_LABELS: 1-5 -> Wary/Civil/Warm/Trusted/Bonded. */
inline char const* TierLabel(int tier)
{
    switch (tier)
    {
        case 1: return "Wary";
        case 2: return "Civil";
        case 3: return "Warm";
        case 4: return "Trusted";
        case 5: return "Bonded";
        default: return "Warm";
    }
}

/** DB storage tier -> trained tier number (A5: stranger/acquaintance/ally/
 * trusted map onto the trained 1-5 scale; bonded is the >=120 derivation). */
inline int TierFromStorage(std::string const& tier)
{
    if (tier == "stranger") return 1;
    if (tier == "acquaintance") return 2;
    if (tier == "ally") return 3;
    if (tier == "trusted") return 4;
    if (tier == "bonded") return 5;
    return 1;
}

/** Trained tier number -> the storage/trait spelling (5 is derived on
 * READ: the schema's enum/CHECK pins the four STORED values, so 'bonded'
 * only ever exists as this display/trait spelling, never in the column). */
inline char const* TierStorageName(int tier)
{
    switch (tier)
    {
        case 5: return "bonded";
        case 4: return "trusted";
        case 3: return "ally";
        case 2: return "acquaintance";
        default: return "stranger";
    }
}

/** banklib.an(): "a dwarf" / "an orc". */
inline std::string An(std::string const& word)
{
    char const first = word.empty() ? 'a' : (char)std::tolower((unsigned char)word[0]);
    return (first == 'a' || first == 'e' || first == 'i' || first == 'o' || first == 'u')
        ? ("an " + word) : ("a " + word);
}

/** banklib.default_backstory twin. */
inline std::string DefaultBackstory(std::string const& name, std::string const& race,
    std::string const& cls, std::string const& role, std::string const& zone,
    std::string const& quirks, std::string const& never)
{
    std::string out = name + " is a " + race + " " + cls + " - " + role +
        " - making a life in " + zone + ".";
    if (!quirks.empty())
        out += " Traits: " + quirks + ".";
    if (!never.empty())
        out += " Never: " + never + ".";
    return out;
}

/** Deterministic TOOLS_NOTE variant for a card id (banklib.tools_note_for:
 * crc32(str(id)) % 4 - F7 example-block rotation). */
inline char const* ToolsNoteForCardId(std::string const& cardId)
{
    static char const* const variants[4] = {
        training::TOOLS_NOTE_A, training::TOOLS_NOTE_B,
        training::TOOLS_NOTE_C, training::TOOLS_NOTE_D,
    };
    return variants[Crc32Str(cardId) % 4];
}

/** Deterministic production bible for a card id (same hash discipline). */
inline char const* BibleForCardId(std::string const& cardId)
{
    static char const* const bibles[4] = {
        training::BIBLE_GRUMPH, training::BIBLE_GROMNAK,
        training::BIBLE_MAERA, training::BIBLE_THREN,
    };
    return bibles[Crc32Str(cardId) % 4];
}

/** banklib.apply_player twin: swap {player} and the legacy fixed name for
 * the row's identity (case-insensitive on the legacy name). */
inline std::string ApplyPlayer(std::string const& text, std::string const& playerName)
{
    static std::string const kLegacy = "daevin";
    std::string out;
    out.reserve(text.size());
    for (size_t i = 0; i < text.size();)
    {
        if (text.compare(i, 8, "{player}") == 0)
        {
            out += playerName;
            i += 8;
            continue;
        }
        bool matched = true;
        for (size_t k = 0; k < kLegacy.size(); ++k)
        {
            if (i + k >= text.size() ||
                std::tolower((unsigned char)text[i + k]) != kLegacy[k])
            {
                matched = false;
                break;
            }
        }
        if (matched)
        {
            out += playerName;
            i += kLegacy.size();
            continue;
        }
        out += text[i];
        ++i;
    }
    return out;
}

/** The plain inputs banklib.sysm_for_card consumes (card + player sides). */
struct PromptPersona
{
    std::string id;        // stable card id - TOOLS_NOTE/bible selection key
    std::string name;
    std::string race;      // "dwarf"
    std::string cls;       // "warrior"
    std::string role;      // "smith" / "adventurer"
    std::string zone;      // "Elwynn Forest"
    bool companion = false;
    std::string bible;     // the training bible text (BibleForCardId)
    std::string backstory; // empty -> DefaultBackstory
    std::string quirks;    // optional traits (default backstory only)
    std::string never;     // optional never-line (default backstory only)
    std::string tierNote;  // optional extra after the tier line
};

struct PromptPlayer
{
    std::string name;
    std::string sex;       // "male" / "female"
    std::string race;
    std::string cls;
    int level = 1;
};

/** banklib.sysm_for_card twin: the trained SYSTEM message. `facts` are the
 * long-term DB facts (third-person); `absence` the rendered absence line;
 * tier 1-5. */
inline std::string SysmForCard(PromptPersona const& c, PromptPlayer const& p,
    int tier, std::string const& absence, std::vector<std::string> const& facts)
{
    std::string ident =
        "You are a roleplaying character in World of Warcraft: Classic. "
        "Your name is " + c.name + ". The player " + p.name +
        " is speaking to you in say and is " + An(p.sex + " " + p.race) + " " + p.cls +
        " of level " + std::to_string(p.level) + ". You are " + An(c.race) + " " + c.cls +
        " - " + c.role + " - that is currently in " + c.zone + ".";
    if (c.companion)
        ident += " You are " + p.name + "'s companion: you travel in their "
                 "party, fight beside them, and share their camp and loot.";
    ident += " Answer as a roleplaying character. Speak as your character speaks.";
    ident += std::string(" ") + training::LEDGER_AVOID_NOTE;

    std::string backstory = c.backstory.empty()
        ? DefaultBackstory(c.name, c.race, c.cls, c.role, c.zone, c.quirks, c.never)
        : c.backstory;

    std::string factsJoin;
    for (size_t i = 0; i < facts.size(); ++i)
    {
        if (i) factsJoin += "; ";
        factsJoin += ApplyPlayer(facts[i], p.name);
    }
    if (factsJoin.empty())
        factsJoin = "none yet worth the name.";

    return ident + "\n" +
        ToolsNoteForCardId(c.id) + "\n" +
        ApplyPlayer(c.bible, p.name) + training::NO_NARRATE + "\n" +
        "Backstory: " + ApplyPlayer(backstory, p.name) + "\n" +
        "Relationship with " + p.name + ": " + TierLabel(tier) +
        " (tier " + std::to_string(tier) + " of 5)." +
        (c.tierNote.empty() ? std::string()
                            : " " + ApplyPlayer(c.tierNote, p.name)) + "\n" +
        (absence.empty()
            ? p.name + " was last seen a few hours ago."
            : ApplyPlayer(absence, p.name)) + "\n" +
        "Facts you remember about " + p.name + ": " + factsJoin;
}

