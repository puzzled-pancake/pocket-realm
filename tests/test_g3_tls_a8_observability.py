# --- A8: the three log lines + req id threading ---------------------------

def test_generate_logs_begin_and_exactly_one_end_per_class(driver):
    payload = driver.PB_LLM_IFACE_CPP_ANDROID
    # entry: id mint, class reset, steady_clock, lane select
    assert "pocketllm::NextReqId()" in payload
    assert 'pocketllm::NoteGenClass("")' in payload
    assert "std::chrono::steady_clock" in payload
    # begin after the governor, with id/bot/lane
    assert '"BotLLM: gen begin req=%llu bot=%u lane=%s"' in payload
    # busy logs end without begin (no generation started)
    assert 'logEnd("busy")' in payload
    # the device lane classifies symmetrically (the A8 scope decision:
    # both lanes log begin/end - not cloud-only)
    assert 'logEnd(raw == "error" ? "error" : "empty")' in payload
    assert 'logEnd("ok")' in payload
    assert 'logEnd("empty")' in payload
    # http/timeout/cap classes outrank the bare shape classes
    assert "pocketllm::GenClassNote()" in payload


