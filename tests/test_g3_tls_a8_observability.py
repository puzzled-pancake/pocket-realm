"""G3 TLS verification + 0.c redaction/debug-gate + A8 observability pins.

The TLS/transport changes live in driver anchor payloads (the working
mirror is regenerated by every build, so pins read the DRIVER and prove
each new anchor still binds its pristine upstream span by applying it to
a scratch copy of the submodule file - the same replace_anchor code the
build runs). The A8 helpers are header-only in PlayerbotLlmFilters.h and
compile on the host directly.

Pinned contracts:
  G3.1  TLS 1.2 floor + SSL_VERIFY_PEER with the staged CA bundle and
        the /system/etc/security/cacerts hashed-dir fallback, all gated
        on LLMTLSVerify (kill-switch restores the unverified handshake)
  G3.2  SSL_set1_host hostname pin inside the verified handshake
  0.c.1 the debug echo redacts Authorization - key bytes never ride
        debugLines under any debug path; the wire request keeps the key
  0.c.1 the .bot isMod force is gone: mod powers need a real moderator
        session (ownerless console events keep them)
  0.c.3 the endpoint parse catch is std::exception (out_of_range from a
        huge port literal) and fails closed - empty endpoint, never a
        silent default port
  A7.4  the concurrency check is >= (the old > admitted max+1); the cap
        is its own class, never "busy"
  A8    dispatch/begin/end lines with a correlating req id at every
        conversational dispatch site; classes busy|cap|timeout|http_%d|
        error|empty|ok; no content bytes ride the lines; the device lane
        classifies symmetrically (both lanes log begin/end)
  keys  LLMTLSVerify/LLMTLSCaFile exist end to end: member, conf read,
        conf.dist documentation
"""
