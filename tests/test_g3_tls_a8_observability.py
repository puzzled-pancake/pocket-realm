@pytest.fixture(scope="module")
def driver():
    spec = importlib.util.spec_from_file_location("driver_g3", DRIVER_PATH)
    module = importlib.util.module_from_spec(spec)
    sys.modules["driver_g3"] = module
    spec.loader.exec_module(module)
    return module


def apply_anchor_to_copy(module, source: Path, old: str, new: str) -> str:
    """Apply one driver anchor to a scratch copy the way the build does;
    returns the patched text (raises through replace_anchor on drift)."""
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / source.name
        shutil.copy2(source, copy)
        module.replace_anchor(copy, old, new)
        return copy.read_text(encoding="utf-8")


# --- G3.1: TLS context anchor -------------------------------------------

def test_tlsctx_anchor_binds_and_sets_verification(driver):
    patched = apply_anchor_to_copy(driver, PRISTINE_IFACE,
                                   driver.PB_IFACE_TLSCTX_UPSTREAM,
                                   driver.PB_IFACE_TLSCTX_ANDROID)
    assert patched.count("SSL_CTX_set_min_proto_version(ctx, TLS1_2_VERSION)") == 1
    assert "SSL_CTX_set_verify(ctx, SSL_VERIFY_PEER, nullptr)" in patched
    # staged bundle first, system hashed-dir store as the fallback
    assert "SSL_CTX_load_verify_locations(\n                    ctx, sPlayerbotAIConfig.llmTlsCaFile.c_str(), nullptr)" in patched
    assert 'SSL_CTX_load_verify_locations(ctx, nullptr, "/system/etc/security/cacerts")' in patched
    # the whole verified path sits behind the kill-switch
    assert "if (sPlayerbotAIConfig.llmTlsVerify)" in patched


