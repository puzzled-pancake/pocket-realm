"""TLS verification + redaction/debug-gate + generation-observability pins.

The TLS/transport changes live in driver anchor payloads (the working
mirror is regenerated by every build, so pins read the DRIVER and prove
each new anchor still binds its pristine upstream span by applying it to
a scratch copy of the submodule file - the same replace_anchor code the
build runs). The observability helpers are header-only in
PlayerbotLlmFilters.h and compile on the host directly.

Pinned contracts:
  TLS   1  TLS 1.2 floor + SSL_VERIFY_PEER with the staged CA bundle and
        the /system/etc/security/cacerts hashed-dir fallback, all gated
        on LLMTLSVerify (kill-switch restores the unverified handshake)
  TLS   2  SSL_set1_host hostname pin inside the verified handshake
  redact  the debug echo redacts Authorization - key bytes never ride
        debugLines under any debug path; the wire request keeps the key
  redact  the .bot isMod force is gone: mod powers need a real moderator
        session (ownerless console events keep them)
  epsafe  the endpoint parse catch is std::exception (out_of_range from a
        huge port literal) and fails closed - empty endpoint, never a
        silent default port
  concur  the concurrency check is >= (the old > admitted max+1); the cap
        is its own class, never "busy"
  observ  dispatch/begin/end lines with a correlating req id at every
        conversational dispatch site; classes busy|cap|timeout|http_%d|
        error|empty|ok; no content bytes ride the lines; the device lane
        classifies symmetrically (both lanes log begin/end)
  OBS*  SCOPE ADJUDICATION: the ledger covers the
        Generate -> GenerateHttp family only - every Generate() caller
        is inside a begin/end by construction (the internal reqId mint).
        Fact extraction/recall are NOT separate generation sites: they
        ride the conversational turn's licensed tool note and dispatch
        through the instrumented SayAction site. The background outbound
        sites (murmur/composer/saga/street/dossier/recap prose) go
        through PostChatHttp and log NOTHING, by design: the
        invariant is scoped "per cloud conversational turn"; the
        chatter workers are exempt
        ("both chatter workers drop silently") and the failure latch is
        their
        observability. Pinned below so a new outbound site that bypasses
        Generate fails loud instead of silently widening the gap.
  keys  LLMTLSVerify/LLMTLSCaFile exist end to end: member, conf read,
        conf.dist documentation
"""
