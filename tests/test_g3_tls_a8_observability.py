def apply_anchor_to_copy(module, source: Path, old: str, new: str) -> str:
    """Apply one driver anchor to a scratch copy the way the build does;
    returns the patched text (raises through replace_anchor on drift)."""
    with tempfile.TemporaryDirectory() as tmp:
        copy = Path(tmp) / source.name
        shutil.copy2(source, copy)
        module.replace_anchor(copy, old, new)
        return copy.read_text(encoding="utf-8")


