def test_a8_helpers_are_header_only_and_host_compilable():
    gxx = shutil.which("g++") or shutil.which("clang++")
    if gxx is None:
        pytest.skip("no host C++ compiler available")
    with tempfile.TemporaryDirectory() as tmp:
        tu = Path(tmp) / "tu.cpp"
        tu.write_text(
            "#include <cstdint>\n"
            "typedef std::uint32_t uint32;  // the server's global typedef, host-side stand-in\n"
            "#include \"PlayerbotLlmFilters.h\"\n"
            "#include <cassert>\n"
            "int main() {\n"
            "    pocketllm::NoteGenClass(\"\");\n"
            "    assert(pocketllm::GenClassNote().empty());\n"
            "    pocketllm::NoteGenClass(\"http_429\");\n"
            "    assert(pocketllm::GenClassNote() == \"http_429\");\n"
            "    uint64_t a = pocketllm::NextReqId();\n"
            "    uint64_t b = pocketllm::NextReqId();\n"
            "    assert(b == a + 1);\n"
            "    return 0;\n"
            "}\n", encoding="utf-8")
        out = Path(tmp) / "tu.exe"
        result = subprocess.run([gxx, "-std=c++11", "-O1", "-Wall",
                                 "-I", str(FILTERS_H.parent), "-o", str(out), str(tu)],
                                capture_output=True, text=True, cwd=str(ROOT))
        assert result.returncode == 0, result.stderr[:2000]
        assert subprocess.run([str(out)], cwd=str(ROOT)).returncode == 0


