def test_cap_class_outranks_the_shape_classes(driver):
    # A concurrency-cap rejection returns an EMPTY body -
    # the transport note is the only signal separating it from a
    # clean-but-empty reply, so the class computation consults the note
    # on EVERY outcome and the fail-quiet arm logs the noted class
    # (never "empty" for a capped turn).
    payload = driver.PB_LLM_IFACE_CPP_ANDROID
    assert ("std::string const genClass = !pocketllm::GenClassNote().empty()\n"
            "        ? pocketllm::GenClassNote()\n"
            "        : (httpBody == \"error\" ? std::string(\"error\") : std::string(\"ok\"));"
            ) in payload
    assert 'logEnd(genClass != "ok" ? genClass.c_str() : "empty");' in payload
    # The legacy-prose-fallback arm carries every
    # transport failure too (the sentinel body "error" is voicable-
    # looking prose, so it lands there) - its end line must log the
    # noted class, never an unconditional "ok"
    legacy_arm = payload.split("response carries no voicable text - staying quiet")[1]
    assert "logEnd(genClass.c_str());" in legacy_arm
    assert 'logEnd("ok");' not in legacy_arm.split("ContentUsable")[0]


def test_a8_lines_carry_no_content(driver):
    # Every BotLLM: format literal in the conversational payloads is one
    # of the fixed-field shapes below - numeric/enum arguments and the
    # sanctioned lane/class/errno strings only. Any new line that could
    # carry body/prompt/reply content (%s of generation text) fails here.
    sanctioned = {
        '"BotLLM: dispatch bot=%u src=%d lane=%s req=%llu"',
        '"BotLLM: gen begin req=%llu bot=%u lane=%s"',
        '"BotLLM: gen end req=%llu bot=%u class=%s durMs=%lu"',
        '"BotLLM: rpgchat daily quota exhausted (%u generations)"',
        '"BotLLM: reply gate refused bot=%u src=%d (once per bot per session)"',
        '"BotLLM: Connection to server failed. Error: %d"',
        '"BotLLM: Connection to server failed. Error: %s"',
        '"BotLLM: HTTP status %d from the LLM endpoint"',
    }
    # The refusal log in the SayAction gate payload joins the scan,
    # so that payload joins the scan (fixed fields only - %u/%d)
    for payload in (driver.PB_SAY_ASYNC_ANDROID, driver.PB_RPG_ASYNC_ANDROID,
                    driver.PB_DEBUG_GEN_ANDROID, driver.PB_LLM_IFACE_CPP_ANDROID,
                    driver.PB_SAY_GATE_ANDROID):
        for fmt in re.findall(r'"BotLLM:[^"]*"', payload):
            assert fmt in sanctioned, (
                f"unsanctioned BotLLM: log literal could carry content: {fmt}")


# --- Observability scope adjudication: the silent background lane ---------
#
# Adjudication: BotLLM: triplets are expected
# only on the conversational dispatch site while background generations
# (street) hit the mock with no ledger lines. The observability law
# covers the conversational family only: reqId plumbs through Generate ->
# GenerateHttp and the run_suite invariant is "per cloud
# conversational turn" - the ledger is the conversational family's
# (SayAction CHAT_REPLY / RpgSubActions RPG_CHAT / Debug DEBUG dispatch
# sites + Generate's own begin/end, which no Generate() caller can
# escape thanks to the internal reqId mint). The background workers are
# exempt BY DESIGN: both chatter workers drop silently - the
# sanctioned observability), and the PostChatHttp law ("callers
# that own their validation chain... fail SILENT"). Note also that the
# fact-licensed
# generation (mock requests.jsonl entry 1) DOES log its full triplet -
# world log req=1 dispatch/begin/end class=ok durMs=215 - because fact
# extraction is the conversational turn's licensed log_fact note, not a
# separate site (BuildTrainedChatRequest's only caller is the SayAction
# dispatch site).

SILENT_BACKGROUND_SITES = {
    # murmur device worker + composer worker + saga worker
    "PlayerbotLlmChatter.cpp": 3,
    # street reaction + weekly dossier reword + session recap prose
    "PlayerbotLlmMemory.cpp": 3,
}


def test_post_chat_http_is_the_adjudicated_silent_lane(driver):
    payload = driver.PB_LLM_IFACE_CPP_ANDROID
    start = payload.index("PostChatHttp(std::string const& body")
    body = payload[start:payload.index("std::string PlayerbotLLMInterface::", start)]
    # delegates straight to GenerateHttp - it never enters Generate, so
    # no begin/end can attach to its callers (the adjudicated design,
    # not an observability gap)
    assert "return GenerateHttp(body, timeOutSeconds, 1, noDebug" in body
    # the S10 silent-fail law is the payload's own contract comment
    assert "fail SILENT" in payload
    # and the lane mints no ledger lines of its own
    assert "BotLLM:" not in body


def test_every_silent_outbound_site_is_sanctioned():
    # The complete outbound-path audit as a pin: the ONLY overlay files
    # that reach an endpoint directly are the six background sites
    # (fact extraction / recall ride the conversational Generate path;
    # the party digest is deterministic, zero calls). Any new
    # PostChatHttp caller - or any overlay reaching GenerateHttp /
    # Generate directly, bypassing the instrumented dispatch sites -
    # fails here and must either route through Generate (gets the
    # ledger for free) or extend this adjudication on purpose.
    patches = ROOT / "native" / "patches" / "playerbots"
    per_file = {}
    for src in sorted(patches.glob("*.cpp")) + sorted(patches.glob("*.h")):
        text = src.read_text(encoding="utf-8", errors="replace")
        assert "PlayerbotLLMInterface::GenerateHttp(" not in text, src.name
        assert "PlayerbotLLMInterface::Generate(" not in text, src.name
        n = text.count("PlayerbotLLMInterface::PostChatHttp(")
        if n:
            per_file[src.name] = n
    assert per_file == SILENT_BACKGROUND_SITES


