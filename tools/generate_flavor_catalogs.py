FLAVORS: dict[str, dict[str, object]] = {
    "tbc": {"binding_class": "WowTbcBindingCatalog", "settings_class": "WowTbcSettingsCatalog",
            "version": "2.4.3", "build": 8606},
    "wotlk": {"binding_class": "WowWotlkBindingCatalog", "settings_class": "WowWotlkSettingsCatalog",
              "version": "3.3.5a", "build": 12340},
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--flavor", choices=sorted(FLAVORS))
    parser.add_argument("--dry-run", action="store_true", help="generate to stdout only")
    args = parser.parse_args()

    flavors = [args.flavor] if args.flavor else sorted(FLAVORS)
    for flavor in flavors:
        manifest = CAPTURE_ROOT / flavor / "manifest.json"
        if not manifest.is_file():
            print(f"ERROR capture missing for {flavor}: run tools/capture_flavor_framexml.py first", file=sys.stderr)
            return 1
        cfg = FLAVORS[flavor]
        binding_kt = generate_bindings(flavor, cfg)
        settings_kt = generate_settings(flavor, cfg)
        if args.dry_run:
            print(f"===== {cfg['binding_class']}.kt =====")
            print(binding_kt)
            print(f"===== {cfg['settings_class']}.kt =====")
            print(settings_kt)
        else:
            bpath = CLIENT_DIR / f"{cfg['binding_class']}.kt"
            spath = INGAME_DIR / f"{cfg['settings_class']}.kt"
            bpath.write_text(binding_kt, encoding="utf-8")
            spath.write_text(settings_kt, encoding="utf-8")
            print(f"wrote {bpath.relative_to(REPO_ROOT)} ({len(binding_kt.splitlines())} lines)")
            print(f"wrote {spath.relative_to(REPO_ROOT)} ({len(settings_kt.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
