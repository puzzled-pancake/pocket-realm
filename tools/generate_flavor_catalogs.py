def generate_bindings(flavor: str, cfg: dict[str, object]) -> str:
    manifest = json.loads((CAPTURE_ROOT / flavor / "manifest.json").read_text(encoding="utf-8"))
    bindings_src = CAPTURE_ROOT / flavor / "Interface" / "FrameXML" / "Bindings.xml"
    strings = parse_global_strings(flavor)
    vanilla = parse_vanilla_bindings()

    root = ET.parse(bindings_src).getroot()
    public: list[ET.Element] = []
    pointer: list[ET.Element] = []
    excluded = {"debug": [], "mac": [], "modifiedClick": []}
    for entry in root:
        if entry.tag == "ModifiedClick":
            excluded["modifiedClick"].append(entry.attrib.get("action"))
            continue
        if entry.attrib.get("debug") == "true":
            excluded["debug"].append(entry.attrib["name"])
            continue
        if entry.attrib.get("platform") == "mac":
            excluded["mac"].append(entry.attrib["name"])
            continue
        if entry.attrib.get("hidden") == "true":
            pointer.append(entry)
            continue
        public.append(entry)

    pointer_ids = [e.attrib["name"] for e in pointer]
    assert set(pointer_ids) == {"TURNORACTION", "CAMERAORSELECTORMOVE"}, pointer_ids

    public_ids = [e.attrib["name"] for e in public]
    assert len(public_ids) == len(set(public_ids))

    rows: list[str] = []
    header_ctx = None
    for entry in public:
        name = entry.attrib["name"]
        header = entry.attrib.get("header") or header_ctx
        if entry.attrib.get("header"):
            header_ctx = entry.attrib["header"]
        label = strings.get(f"BINDING_NAME_{name}")
        assert label, f"no BINDING_NAME_ for {name}"
        van = vanilla.get(name)
        if van:
            description = van["description"]
            advanced = van["advanced"]
        elif name.startswith("MULTICASTACTIONBUTTON"):
            number = name[len("MULTICASTACTIONBUTTON"):]
            description = f"Use totem bar action slot {number}."
            advanced = True
        else:
            description = NEW_DESCRIPTIONS[flavor].get(name)
            assert description, f"author a description for new binding {name}"
            advanced = True
        category = category_for(flavor, name, header or "")
        rows.append(
            f'        key("{name}", {kotlin_str(label)}, WowBindingCategory.{category},\n'
            f'            {kotlin_str(description)}, advanced = {"false" if not advanced else "true"}),'
        )

    pointer_rows = []
    for name in pointer_ids:
        label, description = POINTER_LABELS[name]
        pointer_rows.append(
            "        WowBindingDefinition(\n"
            f'            id = "{name}",\n'
            f'            label = {kotlin_str(label)},\n'
            "            category = WowBindingCategory.INTERNAL_POINTER,\n"
            f'            description = {kotlin_str(description)},\n'
            "            advanced = true,\n"
            "            semantics = WowBindingSemantics.INTERNAL_POINTER_HOLD,\n"
            "        ),"
        )

    public_hash = sha256_lines(public_ids)
    supported_hash = sha256_lines(public_ids + pointer_ids)
    bindings_meta = manifest["framexml"]["Bindings.xml"]

    klass = cfg["binding_class"]
    out = f"""package com.pocketrealm.client

/**
 * Versioned manifest of supported stock key-binding IDs from WoW {cfg["version"]} (build {cfg["build"]}).
 *
 * GENERATED by tools/generate_flavor_catalogs.py from the flavor capture in
 * out/flavor-capture/{flavor} (tools/capture_flavor_framexml.py) — do not
 * hand-edit; regenerate. Primary source: the staged genuine client's own
 * `Interface\\FrameXML\\Bindings.xml` extracted from {bindings_meta["sourceMpq"]}
 * ({bindings_meta["bytes"]} bytes, sha256 {bindings_meta["sha256"]}), with labels
 * from the same capture's GlobalStrings.lua `BINDING_NAME_*` strings.
 *
 * The public list excludes, exactly like the vanilla 1.12.1 precedent
 * (WowVanillaBindingCatalog): the {len(excluded['debug'])} hidden debug bindings
 * ({', '.join(excluded['debug'][:4])}…), the {len(excluded['mac'])} Mac-only
 * iTunes/movie-recording bindings, and the {len(excluded['modifiedClick'])}
 * `<ModifiedClick>` modifier gestures (not rows of the key-binding screen in
 * this client family). The {len(pointer_ids)} active hidden mouse gestures are
 * retained in [internalPointer] for runtime integration and must not appear in
 * the normal action picker; the 1.12.1 CAMERAORSELECTORMOVESTICKY gesture was
 * REMOVED in 2.x (verified: no such name in the captured Bindings.xml).
 *
 * Deliberately absent versus vanilla: `stockKeyBindings`/`reservedKeys`.
 * Vanilla's default-key pins came from a live `bindings-cache.wtf` device
 * capture; no in-world session exists for this flavor yet (unattended
 * campaign), and inventing default keys would be exactly the fabrication the
 * capture-then-hash rule exists to prevent. They land with the device round.
 */
object {klass} {{
    const val CATALOG_VERSION: Int = 1
    const val WOW_CLIENT_VERSION: String = "{cfg["version"]}"
    const val WOW_CLIENT_BUILD: Int = {cfg["build"]}
    /** Effective Bindings.xml of the staged client (capture manifest pin). */
    const val SOURCE_MPQ: String = "{bindings_meta["sourceMpq"]}"
    const val SOURCE_SHA256: String = "{bindings_meta["sha256"]}"
    /** SHA-256 of the {len(public_ids)} public IDs joined in source order with `\\n`. */
    const val PUBLIC_ID_ORDER_SHA256: String =
        "{public_hash}"
    /** SHA-256 of the public IDs followed by the {len(pointer_ids)} hidden pointer IDs. */
    const val SUPPORTED_ID_ORDER_SHA256: String =
        "{supported_hash}"
    const val PUBLIC_COUNT: Int = {len(public_ids)}
    const val SUPPORTED_COUNT: Int = {len(public_ids) + len(pointer_ids)}

    private fun key(
        id: String,
        label: String,
        category: WowBindingCategory,
        description: String,
        advanced: Boolean = true,
    ) = WowBindingDefinition(
        id = id,
        label = label,
        category = category,
        description = description,
        advanced = advanced,
        semantics = WowBindingSemantics.KEY_LIKE,
    )

    /** Active, non-debug, non-platform-specific bindings in stock source order. */
    val userFacing: List<WowBindingDefinition> = listOf(
{chr(10).join(rows)}
    )

    /** Active stock hidden bindings, kept separate from the normal user-facing catalog. */
    val internalPointer: List<WowBindingDefinition> = listOf(
{chr(10).join(pointer_rows)}
    )

    /** All supported active IDs. This adds the internal pointer bindings after source-order UI IDs. */
    val allSupported: List<WowBindingDefinition> = buildList {{
        addAll(userFacing)
        addAll(internalPointer)
    }}

    /** Compact set appropriate for a first controller-layout screen. */
    val basicRecommended: List<WowBindingDefinition> =
        userFacing.filterNot(WowBindingDefinition::advanced)

    private val byId: Map<String, WowBindingDefinition> =
        allSupported.associateBy(WowBindingDefinition::id)

    fun find(id: String): WowBindingDefinition? = byId[id]

    fun inCategory(
        category: WowBindingCategory,
        includeAdvanced: Boolean = true,
    ): List<WowBindingDefinition> = userFacing.filter {{ binding ->
        binding.category == category && (includeAdvanced || !binding.advanced)
    }}

    /** Case-insensitive search over the stable ID, label, and short explanation. */
    fun search(
        query: String,
        categories: Set<WowBindingCategory> = emptySet(),
        includeAdvanced: Boolean = true,
        includeInternal: Boolean = false,
    ): List<WowBindingDefinition> {{
        val needle = query.trim()
        val source = if (includeInternal) allSupported else userFacing
        return source.filter {{ binding ->
            (categories.isEmpty() || binding.category in categories) &&
                (includeAdvanced || !binding.advanced) &&
                (needle.isEmpty() ||
                    binding.id.contains(needle, ignoreCase = true) ||
                    binding.label.contains(needle, ignoreCase = true) ||
                    binding.description.contains(needle, ignoreCase = true))
        }}
    }}
}}
"""
    return out


