def category_for(flavor: str, name: str, header: str) -> str:
    """Map a captured binding to the shared WowBindingCategory enum member."""
    if name.startswith("MULTICAST"):
        return "TOTEM_BAR"
    if name.startswith("VEHICLE"):
        return "VEHICLE_CONTROLS"
    if name.startswith("MULTIACTIONBAR"):
        return "MULTI_ACTION_BARS"
    if name.startswith("ACTIONBUTTON"):
        return "MAIN_ACTION_BAR"
    if name.startswith("SHAPESHIFTBUTTON"):
        return "SHAPESHIFT_BAR"
    if name.startswith("BONUSACTIONBUTTON"):
        return "BONUS_ACTION_BAR"
    if name.startswith(("ACTIONPAGE",)) or name in (
        "PREVIOUSACTIONPAGE", "NEXTACTIONPAGE", "TOGGLEACTIONBARLOCK", "TOGGLEAUTOSELFCAST",
    ):
        return "ACTION_PAGES"
    if name.startswith(("TOGGLEBACKPACK", "TOGGLEBAG", "OPENALLBAGS", "TOGGLEKEYRING")):
        return "BAGS"
    if header in ("MOVEMENT", "CHAT", "TARGETING", "CAMERA", "MISC"):
        return {
            "MOVEMENT": "MOVEMENT",
            "CHAT": "CHAT",
            "TARGETING": "TARGETING",
            "CAMERA": "CAMERA",
            "MISC": "MISCELLANEOUS",
        }[header]
    if header in ("ACTIONBAR", "MULTIACTIONBAR", "INTERFACE"):
        return "CHARACTER_AND_UI"
    if header.startswith("BLANK"):
        return "MULTI_ACTION_BARS" if name.startswith("MULTIACTIONBAR") else "TOTEM_BAR"
    return "MISCELLANEOUS"


