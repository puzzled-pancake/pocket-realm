#!/usr/bin/env python3
"""Generate the tbc/wotlk binding + settings catalogs from the flavor capture.

Companion of tools/capture_flavor_framexml.py (run that first). Reads
out/flavor-capture/<flavor>/ — the effective FrameXML sources extracted from
the staged genuine client's locale MPQ chain plus the exe window-signature
scan — and emits:

    android/app/src/main/java/com/pocketrealm/client/WowTbcBindingCatalog.kt
    android/app/src/main/java/com/pocketrealm/client/WowWotlkBindingCatalog.kt
    android/app/src/main/java/com/pocketrealm/ingame/WowTbcSettingsCatalog.kt
    android/app/src/main/java/com/pocketrealm/ingame/WowWotlkSettingsCatalog.kt

Every catalog fact is capture-then-hash exactly like the vanilla 109/211
precedent (WowVanillaSettingsCatalog / WowVanillaBindingCatalog):

- binding IDs, their source order, headers, runOnUp flags and the
  debug/mac/hidden exclusion verdicts come from the captured Bindings.xml;
- binding labels come from the captured GlobalStrings.lua BINDING_NAME_*
  strings (the 2.x/3.x label mechanism — 1.12.1 had none, which is why the
  vanilla catalog hand-authored them);
- settings rows (cvar keys, label keys, slider ranges, captured defaults)
  come from the captured option-panel Lua (SoundOptionsFrame /
  UIOptionsPanels for tbc, Video/Audio/InterfaceOptionsPanels for wotlk)
  and their labels from the captured GlobalStrings.lua;
- PUBLIC_ID_ORDER_SHA256 / SUPPORTED_ID_ORDER_SHA256 / ID_ORDER_SHA256 are
  computed from the emitted rows so the Kotlin pins and the generated bytes
  cannot drift apart.

What is deliberately NOT fabricated: stock default KEYS (vanilla's
bindings-cache.wtf device capture has no tbc/wotlk equivalent — those need
an in-world session, which the unattended campaign cannot run), captured
CVar DEFAULT VALUES beyond ones the FrameXML itself states, and the vanilla
video-panel row set for tbc (its native panel has no FrameXML source; only
rows whose keys the staged client's own Config.wtf write-out carries are
emitted, provenance STAGED_CLIENT_WTF).

App-authored overlays (documented as such in the emitted KDoc): binding
descriptions inherited from the vanilla catalog for IDs that survived
unchanged plus new one-liners for 2.x/3.x additions, category grouping,
`advanced` curation inherited from vanilla, settings group names, the
managed-display fixed rows, and the sticky-targeting / spam-filter inverse
flags (same cvar semantics as vanilla).

Usage:
    python tools/generate_flavor_catalogs.py [--flavor tbc|wotlk] [--dry-run]

Exit codes: 0 = generated (or verified in dry-run), 1 = capture missing.
"""
