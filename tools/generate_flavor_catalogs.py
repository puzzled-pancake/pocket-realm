# --------------------------------------------------------------------------- helpers


def sha256_lines(lines: list[str]) -> str:
    return hashlib.sha256(("\n".join(lines) + "\n").encode("utf-8")).hexdigest()


def kotlin_str(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def parse_global_strings(flavor: str) -> dict[str, str]:
    text = (CAPTURE_ROOT / flavor / "Interface" / "FrameXML" / "GlobalStrings.lua").read_text(encoding="latin1")
    return dict(re.findall(r'([A-Z0-9_]+)\s*=\s*"([^"]*)"', text))


def parse_vanilla_bindings() -> dict[str, dict[str, object]]:
    """id -> {label, category, description, advanced} from the vanilla catalog."""
    text = VANILLA_BINDING.read_text(encoding="utf-8")
    entries: dict[str, dict[str, object]] = {}
    # The catalog builds rows with key("ID", "label", category, "description"[, false])
    row = re.compile(
        r'add\(key\(\s*"(?P<id>[A-Z0-9_]+)",\s*"(?P<label>[^"]*)",\s*(?P<cat>[\w.]+),\s*'
        r'"(?P<desc>(?:[^"\\]|\\.)*)"(?:\s*,\s*(?P<adv>false|true))?\s*\)\)',
    )
    for m in row.finditer(text):
        entries[m.group("id")] = {
            "label": m.group("label"),
            "category": m.group("cat"),
            "description": m.group("desc"),
            "advanced": m.group("adv") != "false",  # key() default is advanced = true
        }
    numbered = re.compile(
        r'numbered\(\s*"(?P<prefix>[A-Z]+)",\s*"(?P<label>[^"]*)",\s*"(?P<desc>(?:[^"\\]|\\.)*)",\s*'
        r'(?P<count>\d+),\s*(?P<cat>[\w.]+),\s*advanced\s*=\s*(?P<adv>false|true)\s*\)(?P<drop>\.drop\(1\))?',
    )
    for m in numbered.finditer(text):
        start = 2 if m.group("drop") else 1
        for i in range(start, int(m.group("count")) + 1):
            entries[f"{m.group('prefix')}{i}"] = {
                "label": f"{m.group('label')} {i}",
                "category": m.group("cat"),
                "description": f"{m.group('desc')} {i}.",
                "advanced": m.group("adv") == "true",
            }
    # The multibar rows are built by a (1..4).forEach loop in the source —
    # mirror its exact emission so shared IDs inherit vanilla curation.
    for bar in range(1, 5):
        for button in range(1, 13):
            entries[f"MULTIACTIONBAR{bar}BUTTON{button}"] = {
                "label": f"Additional bar {bar} action {button}",
                "category": "WowBindingCategory.MULTI_ACTION_BARS",
                "description": f"Use action on additional bar {bar}, slot {button}.",
                "advanced": True,
            }
    return entries


