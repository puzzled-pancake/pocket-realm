SLIDER_RE = re.compile(
    r'minValue\s*=\s*(-?[\d.]+)\s*,\s*maxValue\s*=\s*(-?[\d.]+)\s*(?:,\s*valueStep\s*=\s*(-?[\d.]+))?'
)


def parse_panel_tables(lua_text: str) -> list[tuple[str, list[dict[str, object]]]]:
    tables: list[tuple[str, list[dict[str, object]]]] = []
    for m in re.finditer(r'(\w+PanelOptions) = \{(.*?)\n\}', lua_text, re.S):
        name, body = m.group(1), m.group(2)
        rows = []
        for rm in re.finditer(r'(\w+)\s*=\s*\{([^}]*)\}', body):
            key, rest = rm.group(1), rm.group(2)
            text = re.search(r'text\s*=\s*"([^"]*)"', rest)
            if not text:
                continue
            row: dict[str, object] = {"key": key, "text": text.group(1)}
            rng = SLIDER_RE.search(rest)
            if rng:
                row["min"] = float(rng.group(1))
                row["max"] = float(rng.group(2))
                row["step"] = float(rng.group(3)) if rng.group(3) else None
            default = re.search(r'default\s*=\s*"([^"]*)"', rest)
            if default:
                row["default"] = default.group(1)
            rows.append(row)
        if rows:
            tables.append((name, rows))
    return tables


def camel(key: str) -> str:
    head, *rest = key.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


